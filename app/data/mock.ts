function totalOf(items: InvoiceItem[]): number {
  return items.reduce((sum, it) => {
    const gross = it.quantity * it.unitPrice;
    const net = gross - (gross * it.discount) / 100;
    return sum + net + (net * it.tax) / 100;
  }, 0);
}

